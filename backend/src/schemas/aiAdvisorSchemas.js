import { z } from 'zod';

export const advisoryRequestSchema = z.object({
  reporting_period: z.enum(['all', 'last_30_days', 'last_90_days', 'current_term']).default('all'),
  student_question: z.string().trim().max(500).optional().nullable(),
  weak_topics: z
    .union([z.string().trim().max(500), z.array(z.string().trim().max(100))])
    .optional()
    .nullable()
    .transform((val) => {
      if (!val) return [];
      if (Array.isArray(val)) return val;
      return val.split(',').map((s) => s.trim()).filter(Boolean);
    }),
  request_type: z.enum(['performance_analysis', 'study_recommendations', 'weekly_study_plan']).default('performance_analysis'),
});

// Zod schema to strictly validate structured JSON responses generated by Gemini
export const aiAnalysisResponseSchema = z.object({
  summary: z.string(),
  performance_assessment: z.string(),
  strengths: z.array(
    z.object({
      subject: z.string(),
      observation: z.string(),
      evidence: z.string(),
    })
  ).default([]),
  areas_for_improvement: z.array(
    z.object({
      subject: z.string(),
      gap: z.string(),
      priority: z.enum(['high', 'medium', 'low']),
      recommended_action: z.string(),
    })
  ).default([]),
  priority_actions: z.array(z.string()).default([]),
  revision_strategies: z.array(
    z.object({
      title: z.string(),
      method: z.string(),
      frequency: z.string(),
    })
  ).default([]),
  encouragement: z.string(),
});

export const aiStudyPlanResponseSchema = z.object({
  title: z.string(),
  rationale: z.string(),
  suggested_days: z.number().int().min(1).max(30).default(7),
  tasks: z.array(
    z.object({
      title: z.string(),
      description: z.string().optional().default(''),
      subject_name: z.string(),
      estimated_minutes: z.number().int().min(15).max(180).default(45),
      priority: z.enum(['high', 'medium', 'low']).default('medium'),
      activity_type: z.enum([
        'concept_revision',
        'practice_questions',
        'assignment_completion',
        'mock_test',
        'error_review',
        'spaced_revision',
        'time_management',
        'topic_specific_practice',
      ]).default('practice_questions'),
    })
  ),
});
